import type { SeedInput } from "./files";
import {
  insertRows,
  intArray,
  jsonb,
  literal,
  quote,
  textArray,
  tuple,
  updateExcluded,
  type SqlValue,
} from "./sql";

export type RenderResult = { sql: string; warnings: string[]; counts: Record<string, number> };

/**
 * Turn the seed files into one idempotent SQL script. Running it twice gives
 * the same database state: catalog rows are upserted, per-hero child rows
 * (skills, relations, builds) are replaced, and stat snapshots are upserted
 * by (rank, period, date) with their rows replaced.
 */
export function renderSeedSql(input: SeedInput): RenderResult {
  const { official, tags, itemOverrides } = input;
  const warnings: string[] = [];
  const counts: Record<string, number> = {};
  const out: string[] = [];

  const heroIds = new Set(official.heroes.map((h) => h.id));
  const heroIdBySlug = new Map(official.heroes.map((h) => [h.slug, h.id]));
  const itemIds = new Set(official.items.map((i) => i.id));
  const emblemIds = new Set(official.emblems.map((e) => e.id));
  const talentIds = new Set(official.talents.map((t) => t.id));
  const spellIds = new Set(official.spells.map((s) => s.id));
  const heroIdList = [...heroIds].sort((a, b) => a - b);

  const keepHero = (id: number, what: string) => {
    if (heroIds.has(id)) return true;
    warnings.push(`${what}: hero ${id} is not in heroes.json, skipped`);
    return false;
  };
  const known = (id: number | null, set: Set<number>, what: string) => {
    if (id === null) return null;
    if (set.has(id)) return id;
    warnings.push(`${what}: id ${id} not found, stored as null`);
    return null;
  };

  out.push(
    "-- Generated by scripts/seed/render-sql.ts from the files in seed/.",
    "-- Do not edit by hand: change the JSON files and run `pnpm seed:sql` again.",
    `-- Official snapshot fetched at ${official.meta.fetched_at}.`,
    "",
    "begin;",
    "",
  );

  // Heroes ------------------------------------------------------------------
  const heroColumns = [
    "id", "slug", "name", "roles", "lanes", "specialties", "durability", "offense",
    "control_effect", "difficulty", "lore", "head_image_url", "portrait_image_url", "is_active",
  ];
  out.push("-- Heroes", insertRows(
    "public.heroes",
    heroColumns,
    official.heroes.map((h) => [
      h.id, h.slug, h.name, textArray(h.roles, "public.hero_role"), textArray(h.lanes, "public.hero_lane"),
      textArray(h.specialties), h.durability, h.offense, h.control_effect, h.difficulty, h.lore,
      h.head_image_url, h.portrait_image_url, h.is_active ?? true,
    ]),
    `on conflict (id) do update ${updateExcluded(heroColumns.slice(1))}`,
  ));
  counts.heroes = official.heroes.length;

  // Skills and relations: replaced per hero --------------------------------
  if (heroIdList.length > 0) {
    out.push(
      "-- Skills and official relations are replaced for every seeded hero",
      `delete from public.hero_skills where hero_id = any(${literal(intArray(heroIdList))});`,
      `delete from public.hero_relations where hero_id = any(${literal(intArray(heroIdList))});`,
      "",
    );
  }
  const skills = official.skills.filter((s) => keepHero(s.hero_id, "skill"));
  out.push(insertRows(
    "public.hero_skills",
    ["hero_id", "slot", "source_skill_id", "name", "description", "cooldown", "cost", "tags", "icon_url"],
    skills.map((s) => [
      s.hero_id, s.slot, s.source_skill_id, s.name, s.description, s.cooldown, s.cost, textArray(s.tags), s.icon_url,
    ]),
    "on conflict (hero_id, slot) do nothing",
  ));
  counts.skills = skills.length;

  const relations = official.relations.filter(
    (r) => keepHero(r.hero_id, "relation") && keepHero(r.target_hero_id, "relation target") && r.hero_id !== r.target_hero_id,
  );
  out.push(insertRows(
    "public.hero_relations",
    ["hero_id", "relation", "target_hero_id", "description"],
    relations.map((r) => [r.hero_id, r.relation, r.target_hero_id, r.description]),
    "on conflict do nothing",
  ));
  counts.relations = relations.length;

  // Curated tags -------------------------------------------------------------
  const tagRows: SqlValue[][] = [];
  for (const [slug, values] of Object.entries(tags)) {
    const heroId = heroIdBySlug.get(slug);
    if (heroId === undefined) {
      warnings.push(`hero-tags.json: "${slug}" does not match any hero slug, skipped`);
      continue;
    }
    tagRows.push([
      heroId, values.damage_type, values.frontline, values.hard_cc, values.peel, values.aoe_damage,
      values.pickoff, values.push, values.mobility, values.sustain, values.burst, values.scaling,
      values.needs_review ?? false, values.notes ?? null,
    ]);
  }
  const untagged = official.heroes.filter((h) => !(h.slug in tags)).map((h) => h.slug);
  if (untagged.length > 0) warnings.push(`hero-tags.json has no entry for: ${untagged.join(", ")}`);
  const tagColumns = [
    "hero_id", "damage_type", "frontline", "hard_cc", "peel", "aoe_damage", "pickoff", "push",
    "mobility", "sustain", "burst", "scaling", "needs_review", "notes",
  ];
  out.push("-- Curated composition tags (seed/hero-tags.json)", insertRows(
    "public.hero_tags",
    tagColumns,
    tagRows,
    `on conflict (hero_id) do update ${updateExcluded(tagColumns.slice(1))}`,
  ));
  counts.tags = tagRows.length;

  // Items, emblems, talents, spells -----------------------------------------
  const itemColumns = [
    "id", "slug", "name", "category", "tier", "price", "attributes", "passives", "builds_into", "icon_url", "is_active",
  ];
  const unknownOverrides = Object.keys(itemOverrides).filter((slug) => !official.items.some((i) => i.slug === slug));
  for (const slug of unknownOverrides) warnings.push(`overrides/items.json: "${slug}" matches no item, skipped`);
  out.push("-- Items (with seed/overrides/items.json applied)", insertRows(
    "public.items",
    itemColumns,
    official.items.map((item) => {
      const merged = { ...item, ...itemOverrides[item.slug] };
      return [
        merged.id, merged.slug, merged.name, merged.category, merged.tier, merged.price, jsonb(merged.attributes),
        jsonb(merged.passives), intArray(merged.builds_into), merged.icon_url, merged.is_active ?? true,
      ];
    }),
    `on conflict (id) do update ${updateExcluded(itemColumns.slice(1))}`,
  ));
  counts.items = official.items.length;

  const emblemColumns = ["id", "slug", "name", "attributes", "icon_url", "recommended_roles", "sort_order"];
  out.push("-- Emblem sets", insertRows(
    "public.emblems",
    emblemColumns,
    official.emblems.map((e) => [
      e.id, e.slug, e.name, jsonb(e.attributes), e.icon_url, textArray(e.recommended_roles, "public.hero_role"), e.sort_order,
    ]),
    `on conflict (id) do update ${updateExcluded(emblemColumns.slice(1))}`,
  ));
  counts.emblems = official.emblems.length;

  const talentColumns = ["id", "name", "tier", "description", "icon_url", "sort_order"];
  out.push("-- Emblem talents", insertRows(
    "public.emblem_talents",
    talentColumns,
    official.talents.map((t) => [t.id, t.name, t.tier, t.description, t.icon_url, t.sort_order]),
    `on conflict (id) do update ${updateExcluded(talentColumns.slice(1))}`,
  ));
  counts.talents = official.talents.length;

  const spellColumns = ["id", "slug", "name", "description", "short_description", "icon_url", "sort_order"];
  out.push("-- Battle spells", insertRows(
    "public.battle_spells",
    spellColumns,
    official.spells.map((s) => [s.id, s.slug, s.name, s.description, s.short_description, s.icon_url, s.sort_order]),
    `on conflict (id) do update ${updateExcluded(spellColumns.slice(1))}`,
  ));
  counts.spells = official.spells.length;

  // Recommended builds: replaced per (hero, bracket) ---------------------------
  const builds = official.builds.filter((b) => keepHero(b.hero_id, "build"));
  const buildScopes = [...new Set(builds.map((b) => `${b.hero_id}|${b.rank_bracket}`))].map((key) => {
    const [heroId, bracket] = key.split("|");
    return `(${Number(heroId)}, ${quote(bracket!)}::public.rank_bracket)`;
  });
  if (buildScopes.length > 0) {
    out.push(
      "-- Recommended builds are replaced for every seeded hero and rank",
      `delete from public.hero_recommended_builds where (hero_id, rank_bracket) in (\n  ${buildScopes.join(",\n  ")}\n);`,
      "",
    );
  }
  out.push(insertRows(
    "public.hero_recommended_builds",
    [
      "hero_id", "lane", "rank_bracket", "build_rank", "emblem_id", "talent_t1_id", "talent_t2_id",
      "talent_t3_id", "battle_spell_id", "pick_rate", "win_rate",
    ],
    builds.map((b) => [
      b.hero_id, b.lane, b.rank_bracket, b.build_rank,
      known(b.emblem_id, emblemIds, "build emblem"),
      known(b.talent_t1_id, talentIds, "build talent"),
      known(b.talent_t2_id, talentIds, "build talent"),
      known(b.talent_t3_id, talentIds, "build talent"),
      known(b.battle_spell_id, spellIds, "build spell"),
      b.pick_rate, b.win_rate,
    ]),
    "on conflict (hero_id, lane, rank_bracket, build_rank) do nothing",
  ));
  counts.builds = builds.length;

  const buildItemValues: string[] = [];
  for (const b of builds) {
    b.item_ids.forEach((itemId, index) => {
      if (!itemIds.has(itemId)) {
        warnings.push(`build for hero ${b.hero_id}: item ${itemId} not found, skipped`);
        return;
      }
      buildItemValues.push(tuple([b.hero_id, b.lane, b.rank_bracket, b.build_rank, index + 1, itemId]));
    });
  }
  if (buildItemValues.length > 0) {
    out.push(
      "insert into public.hero_build_items (build_id, slot, item_id)",
      "select b.id, v.slot, v.item_id",
      `from (values\n  ${buildItemValues.join(",\n  ")}\n) as v (hero_id, lane, rank_bracket, build_rank, slot, item_id)`,
      "join public.hero_recommended_builds b",
      "  on b.hero_id = v.hero_id and b.lane = v.lane::public.hero_lane",
      "  and b.rank_bracket = v.rank_bracket::public.rank_bracket and b.build_rank = v.build_rank",
      "on conflict (build_id, slot) do update set item_id = excluded.item_id;",
      "",
    );
  }
  counts.buildItems = buildItemValues.length;

  // Statistics snapshot ---------------------------------------------------------
  const snapshots = official.snapshots;
  if (snapshots.length > 0) {
    const statRows = snapshots.reduce((n, s) => n + s.stats.length, 0);
    const snapshotValues = snapshots.map((s) =>
      tuple([
        s.rank_bracket, s.period_days, s.snapshot_date, s.fetched_at, s.content_hash,
        s.stats.filter((r) => heroIds.has(r.hero_id)).length, Boolean(s.matchups?.length || s.synergies?.length),
      ]),
    );
    out.push(
      "-- Statistics snapshot, published immediately (this whole script is one transaction)",
      "with seed_run as (",
      "  insert into public.data_update_logs (job, status, triggered_by, finished_at, rows_written, message)",
      `  values ('seed', 'success', 'manual', now(), ${statRows}, ${quote(`Seed from the official data snapshot fetched at ${official.meta.fetched_at}`)})`,
      "  returning id",
      ")",
      "insert into public.stat_snapshots (rank_bracket, period_days, snapshot_date, fetched_at, content_hash, hero_count, has_matchups, is_published, run_id)",
      "select v.rank_bracket::public.rank_bracket, v.period_days, v.snapshot_date::date, v.fetched_at::timestamptz,",
      "  v.content_hash, v.hero_count, v.has_matchups, true, seed_run.id",
      `from (values\n  ${snapshotValues.join(",\n  ")}\n) as v (rank_bracket, period_days, snapshot_date, fetched_at, content_hash, hero_count, has_matchups)`,
      "cross join seed_run",
      "on conflict (rank_bracket, period_days, snapshot_date) do update set fetched_at = excluded.fetched_at,",
      "  content_hash = excluded.content_hash, hero_count = excluded.hero_count, has_matchups = excluded.has_matchups,",
      "  is_published = true, run_id = excluded.run_id;",
      "",
    );

    const keys = snapshots.map((s) => tuple([s.rank_bracket, s.period_days, s.snapshot_date]));
    const keyJoin = [
      "join public.stat_snapshots s on s.rank_bracket = v.rank_bracket::public.rank_bracket",
      "  and s.period_days = v.period_days and s.snapshot_date = v.snapshot_date::date",
    ];
    for (const table of ["hero_stats", "hero_matchups", "hero_synergies"]) {
      out.push(
        `delete from public.${table} t using public.stat_snapshots s`,
        `where t.snapshot_id = s.id and (s.rank_bracket::text, s.period_days, s.snapshot_date::text) in (\n  ${keys.join(",\n  ")}\n);`,
        "",
      );
    }

    const statValues: string[] = [];
    const matchupValues: string[] = [];
    const synergyValues: string[] = [];
    for (const s of snapshots) {
      const key: SqlValue[] = [s.rank_bracket, s.period_days, s.snapshot_date];
      for (const r of s.stats) {
        if (keepHero(r.hero_id, "stat")) statValues.push(tuple([...key, r.hero_id, r.win_rate, r.pick_rate, r.ban_rate]));
      }
      for (const [rows, target] of [[s.matchups, matchupValues], [s.synergies, synergyValues]] as const) {
        for (const r of rows ?? []) {
          if (r.hero_id === r.other_id || !heroIds.has(r.hero_id) || !heroIds.has(r.other_id)) continue;
          target.push(tuple([...key, r.hero_id, r.other_id, r.win_rate_delta]));
        }
      }
    }

    const pushJoined = (table: string, columns: string, select: string, values: string[], vColumns: string) => {
      for (let i = 0; i < values.length; i += 1000) {
        out.push(
          `insert into public.${table} (${columns})`,
          `select ${select}`,
          `from (values\n  ${values.slice(i, i + 1000).join(",\n  ")}\n) as v (rank_bracket, period_days, snapshot_date, ${vColumns})`,
          ...keyJoin,
          "on conflict do nothing;",
          "",
        );
      }
    };
    pushJoined("hero_stats", "snapshot_id, hero_id, win_rate, pick_rate, ban_rate",
      "s.id, v.hero_id, v.win_rate, v.pick_rate, v.ban_rate", statValues, "hero_id, win_rate, pick_rate, ban_rate");
    pushJoined("hero_matchups", "snapshot_id, hero_id, opponent_id, win_rate_delta",
      "s.id, v.hero_id, v.other_id, v.win_rate_delta", matchupValues, "hero_id, other_id, win_rate_delta");
    pushJoined("hero_synergies", "snapshot_id, hero_id, teammate_id, win_rate_delta",
      "s.id, v.hero_id, v.other_id, v.win_rate_delta", synergyValues, "hero_id, other_id, win_rate_delta");

    counts.snapshots = snapshots.length;
    counts.stats = statValues.length;
    counts.matchups = matchupValues.length;
    counts.synergies = synergyValues.length;
  }

  out.push("commit;", "");
  return { sql: out.join("\n"), warnings, counts };
}
